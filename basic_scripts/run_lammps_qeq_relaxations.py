_LAMMPS_MODULE = None


def lammps_module():
    """Import the LAMMPS Python module once per worker process."""
    global _LAMMPS_MODULE
    if _LAMMPS_MODULE is None:
        import lammps  # type: ignore

        _LAMMPS_MODULE = lammps
