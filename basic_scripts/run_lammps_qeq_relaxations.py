def parse_summary_file(path: Path) -> Dict[str, Any]:
    if not path.is_file():
        return {}
    parsed: Dict[str, Any] = {"events": []}
    with path.open("r", encoding="utf-8") as fh:
        for raw in fh:
            raw = raw.strip()
            if not raw:
                continue
            event: Dict[str, Any] = {}
            for token in raw.split():
                if "=" not in token:
                    continue
                k, v = token.split("=", 1)
                if v in {"nan", "-nan", "inf", "-inf"}:
                    event[k] = v
                    continue
                try:
                    if any(ch in v for ch in ".eE"):
                        event[k] = float(v)
                    else:
                        event[k] = int(v)
                except Exception:
                    event[k] = v
            parsed["events"].append(event)
    if parsed["events"]:
        parsed["final"] = parsed["events"][-1]
    return parsed


