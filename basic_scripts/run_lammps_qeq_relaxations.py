def discover_original_files(
    metadata: Dict[str, Any], job_dir: Path
) -> Tuple[Path, Path]:
    outputs = metadata.get("output_files", {})
    input_file = outputs.get("input_file")
    data_file = outputs.get("data_file")
    if not input_file or not data_file:
        raise ValueError(
            "metadata.json is missing output_files.input_file or output_files.data_file: "
            f"{job_dir}"
        )
    input_path = Path(input_file)
    data_path = Path(data_file)
    if not input_path.is_absolute():
        input_path = (job_dir / input_path).resolve()
    if not data_path.is_absolute():
        data_path = (job_dir / data_path).resolve()
    if not input_path.is_file():
        raise FileNotFoundError(f"Original input file not found: {input_path}")
    if not data_path.is_file():
        raise FileNotFoundError(f"Original data file not found: {data_path}")
    return input_path, data_path


def load_qeq_config(path: Path) -> Dict[str, Any]:
    cfg = load_json(path)
    cfg.setdefault("defaults", {})
    cfg.setdefault("by_force_field_type", {})
    cfg.setdefault("by_lammps_type", {})
    for key in ("defaults", "by_force_field_type", "by_lammps_type"):
        if not isinstance(cfg[key], dict):
            raise ValueError(f"{key} in the QEq configuration must be an object")
    return cfg


def resolve_qeq_params_for_type(
    atom_type: Dict[str, Any],
    qeq_cfg: Dict[str, Any],
) -> Tuple[Dict[str, float], str]:
    defaults = qeq_cfg.get("defaults", {})
    by_ff = qeq_cfg.get("by_force_field_type", {})
    by_lt = qeq_cfg.get("by_lammps_type", {})

    lammps_type = str(atom_type["lammps_type"])
    ff_type = atom_type.get("force_field_type")

    source = None
    raw: Optional[Dict[str, Any]] = None
    if lammps_type in by_lt:
        raw = by_lt[lammps_type]
        source = f"by_lammps_type:{lammps_type}"
    elif ff_type in by_ff:
        raw = by_ff[ff_type]
        source = f"by_force_field_type:{ff_type}"

    if raw is None:
        raise KeyError(
            f"Missing QEq parameters: lammps_type={lammps_type}, force_field_type={ff_type!r}"
        )
    if not isinstance(raw, dict):
        raise TypeError(f"The QEq parameter entry must be an object: {source}")

    merged: Dict[str, float] = {}
    for key in ("chi", "eta", "gamma", "zeta", "qcore", "qmin", "qmax", "omega"):
        value = raw.get(key, defaults.get(key, 0.0))
        merged[key] = float(value)
    return merged, source


def validate_qeq_coverage(
    metadata: Dict[str, Any], qeq_cfg: Dict[str, Any], qeq_style: str
) -> List[Dict[str, Any]]:
    atom_types = metadata.get("atom_types", [])
    if not atom_types:
        raise ValueError("metadata.json does not contain atom_types")

    resolved: List[Dict[str, Any]] = []
    for entry in atom_types:
        params, source = resolve_qeq_params_for_type(entry, qeq_cfg)
        if "chi" not in params or "eta" not in params:
            raise ValueError(f"Atom type {entry.get('lammps_type')} is missing chi/eta")
        if qeq_style == "shielded" and params["gamma"] == 0.0:
            raise ValueError(
                f"qeq/shielded requires nonzero gamma: lammps_type={entry.get('lammps_type')}"
            )
        if qeq_style == "slater" and params["zeta"] == 0.0 and params["qcore"] == 0.0:
            raise ValueError(
                f"qeq/slater generally requires zeta/qcore: lammps_type={entry.get('lammps_type')}"
            )
        resolved.append(
            {
                "lammps_type": int(entry["lammps_type"]),
                "force_field_type": entry.get("force_field_type"),
                "element": entry.get("element"),
                "source": source,
                **params,
            }
        )
    return sorted(resolved, key=lambda x: x["lammps_type"])


def write_qeq_params(path: Path, resolved_rows: List[Dict[str, Any]]) -> None:
    lines = ["# type chi eta gamma zeta qcore qmin qmax omega\n"]
    for row in resolved_rows:
        lines.append(
            f"{row['lammps_type']:d} "
            f"{row['chi']:.16g} {row['eta']:.16g} {row['gamma']:.16g} "
            f"{row['zeta']:.16g} {row['qcore']:.16g} {row['qmin']:.16g} "
            f"{row['qmax']:.16g} {row['omega']:.16g} "
            f"# {row.get('force_field_type', '')} {row.get('element', '')} [{row['source']}]\n"
        )
    path.write_text("".join(lines), encoding="utf-8")


def sanitize_original_input_text(text: str) -> str:
    """
    Keep the original force-field setup, but comment out runtime commands that would
    conflict with the wrapper optimization workflow.
    """
    blacklist_prefixes = [
        "run ",
        "minimize",
        "fix ",
        "unfix ",
        "dump ",
        "dump_modify",
        "undump ",
        "write_data",
        "write_dump",
        "write_restart",
        "restart ",
        "thermo ",
        "thermo_style",
        "thermo_modify",
        "velocity ",
        "reset_timestep",
        "log ",
        "shell ",
        "clear",
        "box ",
        "print ",
        "variable ",
    ]
    lines_out: List[str] = []
    for line in text.splitlines(keepends=True):
        stripped = line.lstrip()
        lowered = stripped.lower()
        if stripped.startswith("#") or stripped == "":
            lines_out.append(line)
            continue
        if any(lowered.startswith(prefix) for prefix in blacklist_prefixes):
            lines_out.append(f"# [run_lammps_qeq_relaxations.py disabled] {line}")
        else:
            lines_out.append(line)
    return "".join(lines_out)


LONG_RANGE_PAIR_TOKENS = (
    "coul/long",
    "tip4p/long",
    "lj/long",
    "buck/long",
    "dipole/long",
)

KSPACE_PAIR_STYLE_FALLBACKS = {
    "lj/cut": "lj/cut/coul/long",
    "lj/cut/coul/cut": "lj/cut/coul/long",
    "buck": "buck/coul/long",
    "buck/coul/cut": "buck/coul/long",
    "coul/cut": "coul/long",
}


def input_supports_kspace(text: str) -> bool:
    """Return True if the original input defines a long-range-compatible pair style."""
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        lowered = stripped.lower()
        if lowered.startswith("pair_style"):
            return any(tok in lowered for tok in LONG_RANGE_PAIR_TOKENS)
    return False


def convert_pair_style_for_kspace(text: str) -> Tuple[str, Dict[str, str]]:
    """Convert a known non-long-range pair style without changing the source file."""
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        body = line.rstrip("\r\n")
        ending = line[len(body) :]
        code, marker, comment = body.partition("#")
        match = re.match(r"^(\s*pair_style\s+)(\S+)(.*)$", code, flags=re.IGNORECASE)
        if match is None:
            continue
        old_style = match.group(2)
        new_style = KSPACE_PAIR_STYLE_FALLBACKS.get(old_style.lower())
        if new_style is None:
            supported = ", ".join(sorted(KSPACE_PAIR_STYLE_FALLBACKS))
            raise ValueError(
                f"pair_style {old_style} cannot be converted automatically to a KSpace-compatible form; "
                f"supported conversions: {supported}. Modify the force field manually or use --use-qeq off."
            )
        lines[index] = (
            f"{match.group(1)}{new_style}{match.group(3)}{marker}{comment}{ending}"
        )
        return "".join(lines), {"from": old_style, "to": new_style}
    raise ValueError(
        "No convertible pair_style command was found in the original input."
    )


def input_has_kspace_style(text: str) -> bool:
    """Return True if the original input already configures a KSpace solver."""
    return any(
        raw.strip().lower().startswith("kspace_style")
        for raw in text.splitlines()
        if raw.strip() and not raw.lstrip().startswith("#")
    )


def build_qeq_fix_command(args: argparse.Namespace, qeq_file_name: str) -> str:
    style = f"qeq/{args.qeq_style}"
    parts = [
        f"fix qeqfix {args.qeq_group} {style} {int(args.qeq_nevery)} {float(args.qeq_cutoff):.16g} "
        f"{qeq_tolerance(args):.16g} {int(args.qeq_maxiter)} {qeq_file_name}"
    ]
    if args.qeq_style in {"dynamic", "fire"}:
        parts.append(
            f" qdamp {float(args.qeq_qdamp):.16g} qstep {float(args.qeq_qstep):.16g}"
        )
    elif args.qeq_style == "slater" and args.slater_alpha is not None:
        parts.append(f" alpha {float(args.slater_alpha):.16g}")
    parts.append(f" warn {args.qeq_warn}")
    return "".join(parts)


def build_box_relax_command(args: argparse.Namespace) -> Optional[str]:
    if args.box_mode == "none" or args.box_cycles <= 0:
        return None
    return (
        f"fix boxrelax all box/relax {args.box_mode} {float(args.box_target):.16g} "
        f"vmax {float(args.box_vmax):.16g}"
    )


def build_optimize_input(
    args: argparse.Namespace,
    metadata: Dict[str, Any],
    base_include_name: str,
    qeq_file_name: str,
    enable_kspace: bool,
    has_kspace_style: bool,
) -> str:
    use_qeq = args.use_qeq == "on"
    qeq_cmd = build_qeq_fix_command(args, qeq_file_name) if use_qeq else ""
    box_cmd = build_box_relax_command(args)
    traj_block = ""
    if args.dump_every > 0:
        traj_block = (
            f"dump relaxdump all custom {int(args.dump_every)} {args.trajectory_name} id type q x y z\n"
            "dump_modify relaxdump sort id\n"
        )

    summary = args.summary_name
    pre_block = ""
    if args.pre_relax == "on":
        pre_block = (
            "# Stage 1: fixed-cell atomic relaxation; QEq is already active when enabled.\n"
            f'print "phase=pre_relax_start" append {summary}\n'
            f"min_style {args.pre_min_style}\n"
            f"min_modify dmax {float(args.pre_dmax):.16g} line {args.pre_line}\n"
            f"minimize {float(args.pre_etol):.16g} {float(args.pre_ftol):.16g} {int(args.pre_maxiter)} {int(args.pre_maxeval)}\n"
            f'print "phase=pre_relax_done step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} qsum=${{qsumv}}" append {summary}\n\n'
        )

    box_cycles_lines = ""
    if box_cmd is not None:
        for cycle in range(1, int(args.box_cycles) + 1):
            box_cycles_lines += (
                f'print "phase=box_relax_start cycle={cycle}" append {summary}\n'
                f"{box_cmd}\n"
                "min_style cg\n"
                f"min_modify dmax {float(args.box_dmax):.16g} line {args.box_line}\n"
                f"minimize {float(args.box_etol):.16g} {float(args.box_ftol):.16g} {int(args.box_maxiter)} {int(args.box_maxeval)}\n"
                "unfix boxrelax\n"
                f'print "phase=box_relax_done cycle={cycle} step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} qsum=${{qsumv}}" append {summary}\n'
            )

    if use_qeq and enable_kspace:
        kspace_block = (
            (
                "# Keep the original long-range solver.\n"
                if has_kspace_style
                else f"# Enable a long-range solver for the compatible pair_style.\n"
                f"kspace_style {args.kspace_style} {float(args.kspace_tol):.16g}\n"
            )
            + "# A nonzero G-ewald is required while all initial charges are zero.\n"
            + f"kspace_modify gewald {float(args.kspace_zero_charge_gewald):.16g}\n\n"
        )
    elif use_qeq:
        kspace_block = (
            "# No long-range-compatible pair_style detected; skip kspace_style.\n\n"
        )
    else:
        kspace_block = "# QEq disabled: preserve the original KSpace configuration.\n\n"

    if use_qeq:
        qeq_block = (
            "# Enable QEq before Stage 1 and keep it active through Stage 2.\n"
            f"{qeq_cmd}\n\n"
            "# One-time precharge before the first minimization.\n"
            "run 0\n"
            f'print "phase=precharge_done step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} qsum=${{qsumv}}" append {summary}\n\n'
            "# Charges now exist, so let LAMMPS choose G-ewald from the requested accuracy.\n"
            "kspace_modify gewald 0.0\n\n"
        )
    else:
        qeq_block = "# QEq disabled: both optimization stages run without charge equilibration.\n\n"

    return f"""# Generated by run_lammps_qeq_relaxations.py v{SCRIPT_VERSION}
# Source job: {metadata.get('job_name', 'unknown')}
# This wrapper reuses the original lammps-interface force-field setup.

include {base_include_name}

{kspace_block}# Wrapper-owned output and minimization controls
thermo 50
thermo_style custom step pe etotal press vol lx ly lz xy xz yz
{traj_block}compute qcharge all property/atom q
compute qsum all reduce sum c_qcharge
variable stepv equal step
variable pev equal pe
variable pressv equal press
variable volv equal vol
variable lxv equal lx
variable lyv equal ly
variable lzv equal lz
variable xyv equal xy
variable xzv equal xz
variable yzv equal yz
variable qsumv equal c_qsum

shell rm -f {summary}
print "phase=begin" append {summary}

{qeq_block}{pre_block}# Stage 2: final optional atom + cell box relaxation.
{box_cycles_lines}# Final state export.
write_data {args.final_data_name}
print "phase=final step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} lx=${{lxv}} ly=${{lyv}} lz=${{lzv}} xy=${{xyv}} xz=${{xzv}} yz=${{yzv}} qsum=${{qsumv}}" append {summary}
"""


def ensure_file_text(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")


def parse_summary_file(path: Path) -> Dict[str, Any]:
    if not path.is_file():
        return {}
    parsed: Dict[str, Any] = {"events": []}
    with path.open("r", encoding="utf-8") as fh:
        for raw in fh:
            raw = raw.strip()
            if not raw:
                continue
            event: Dict[str, Any] = {}
            for token in raw.split():
                if "=" not in token:
                    continue
                k, v = token.split("=", 1)
                if v in {"nan", "-nan", "inf", "-inf"}:
                    event[k] = v
                    continue
                try:
                    if any(ch in v for ch in ".eE"):
                        event[k] = float(v)
                    else:
                        event[k] = int(v)
                except Exception:
                    event[k] = v
            parsed["events"].append(event)
    if parsed["events"]:
        parsed["final"] = parsed["events"][-1]
    return parsed


def build_lammps_command(
    args: argparse.Namespace, optimize_input_name: str, log_name: str
) -> List[str]:
    cmd = shlex.split(args.lmp_cmd)
    if not cmd:
        raise ValueError("--lmp-cmd is empty after parsing")
    cmd += ["-in", optimize_input_name, "-log", log_name]
    return cmd


def write_status(job_dir: Path, payload: Dict[str, Any]) -> None:
    write_json(job_dir / "relax.status.json", payload)


def run_single_job(
    job_dir_str: str, args_dict: Dict[str, Any], qeq_cfg: Dict[str, Any]
) -> Dict[str, Any]:
    args = argparse.Namespace(**args_dict)
    job_dir = Path(job_dir_str).resolve()
    metadata_file = job_dir / "metadata.json"
    start = time.time()

    def finish(result: JobResult) -> Dict[str, Any]:
        return asdict(result)

    try:
        if not metadata_file.is_file():
            raise FileNotFoundError(f"metadata.json not found: {metadata_file}")
        metadata = load_json(metadata_file)
        job_name = metadata.get("job_name", job_dir.name)
        input_path, data_path = discover_original_files(metadata, job_dir)

        final_data_file = job_dir / args.final_data_name
        relax_status_file = job_dir / "relax.status.json"
        qeq_file = job_dir / args.qeq_file_name
        optimize_input_file = job_dir / args.optimize_input_name
        base_include_file = job_dir / args.base_include_name
        summary_file = job_dir / args.summary_name
        log_file = job_dir / args.log_name
        launcher_stdout = job_dir / args.launcher_stdout
        launcher_stderr = job_dir / args.launcher_stderr
        final_dump_file = job_dir / args.trajectory_name

        if args.overwrite:
            for p in [
                qeq_file,
                optimize_input_file,
                base_include_file,
                summary_file,
                log_file,
                launcher_stdout,
                launcher_stderr,
                final_data_file,
                final_dump_file,
                relax_status_file,
            ]:
                try:
                    if p.exists():
                        p.unlink()
                except Exception:
                    pass
        elif final_data_file.exists() and relax_status_file.exists():
            try:
                prev = load_json(relax_status_file)
            except Exception:
                prev = {}
            if args.skip_existing and prev.get("status") == "success":
                return finish(
                    JobResult(
                        job_name=job_name,
                        job_dir=str(job_dir),
                        status="skipped",
                        message="A successful result already exists; skipped by --skip-existing.",
                        duration_sec=time.time() - start,
                        metadata_file=str(metadata_file),
                        input_file=str(input_path),
                        data_file=str(data_path),
                        qeq_file=str(qeq_file),
                        optimize_input_file=str(optimize_input_file),
                        final_data_file=str(final_data_file),
                        final_dump_file=(
                            str(final_dump_file) if final_dump_file.exists() else ""
                        ),
                        log_file=str(log_file) if log_file.exists() else "",
                        summary_file=str(summary_file) if summary_file.exists() else "",
                        launcher_stdout=(
                            str(launcher_stdout) if launcher_stdout.exists() else ""
                        ),
                        launcher_stderr=(
                            str(launcher_stderr) if launcher_stderr.exists() else ""
                        ),
                    )
                )
        original_text = input_path.read_text(encoding="utf-8")
        prepared_text = original_text
        pair_style_conversion: Optional[Dict[str, str]] = None
        enable_kspace = input_supports_kspace(prepared_text)
        if args.use_qeq == "on" and not enable_kspace:
            if args.auto_kspace_pair_style == "on":
                prepared_text, pair_style_conversion = convert_pair_style_for_kspace(
                    prepared_text
                )
                enable_kspace = input_supports_kspace(prepared_text)
            else:
                raise ValueError(
                    "QEq is enabled, but the original pair_style does not support long-range "
                    "electrostatics and automatic conversion is disabled. Use a KSpace-compatible "
                    "*/long pair_style or enable --auto-kspace-pair-style on."
                )
        has_kspace_style = input_has_kspace_style(prepared_text)

        if args.use_qeq == "on":
            resolved_qeq = validate_qeq_coverage(metadata, qeq_cfg, args.qeq_style)
            write_qeq_params(qeq_file, resolved_qeq)
        else:
            resolved_qeq = []
            try:
                if qeq_file.exists():
                    qeq_file.unlink()
            except Exception:
                pass

        base_text = sanitize_original_input_text(prepared_text)
        ensure_file_text(base_include_file, base_text)

        optimize_text = build_optimize_input(
            args,
            metadata,
            base_include_file.name,
            qeq_file.name,
            enable_kspace,
            has_kspace_style,
        )
        ensure_file_text(optimize_input_file, optimize_text)

        lmp_cmd = build_lammps_command(args, optimize_input_file.name, log_file.name)
        with launcher_stdout.open("w", encoding="utf-8") as out, launcher_stderr.open(
            "w", encoding="utf-8"
        ) as err:
            proc = subprocess.run(
                lmp_cmd,
                cwd=job_dir,
                stdout=out,
                stderr=err,
                timeout=args.timeout,
                check=False,
            )

        summary_parsed = parse_summary_file(summary_file)
        ok = proc.returncode == 0 and final_data_file.exists()
        status = "success" if ok else "failed"
        message = (
            "Optimization completed"
            if ok
            else f"LAMMPS returned nonzero exit code: {proc.returncode}"
        )

        status_payload = {
            "script_version": SCRIPT_VERSION,
            "status": status,
            "message": message,
            "job_name": job_name,
            "job_dir": str(job_dir),
            "duration_sec": time.time() - start,
            "returncode": proc.returncode,
            "metadata_file": str(metadata_file),
            "input_file": str(input_path),
            "data_file": str(data_path),
            "qeq_file": str(qeq_file),
            "optimize_input_file": str(optimize_input_file),
            "base_include_file": str(base_include_file),
            "log_file": str(log_file),
            "summary_file": str(summary_file),
            "final_data_file": (
                str(final_data_file) if final_data_file.exists() else None
            ),
            "final_dump_file": (
                str(final_dump_file) if final_dump_file.exists() else None
            ),
            "launcher_stdout": str(launcher_stdout),
            "launcher_stderr": str(launcher_stderr),
            "qeq_settings": {
                "enabled": args.use_qeq == "on",
                "style": args.qeq_style,
                "group": args.qeq_group,
                "nevery": args.qeq_nevery,
                "cutoff": args.qeq_cutoff,
                "tolerance": qeq_tolerance(args),
                "maxiter": args.qeq_maxiter,
                "warn": args.qeq_warn,
                "qdamp": (
                    args.qeq_qdamp if args.qeq_style in {"dynamic", "fire"} else None
                ),
                "qstep": (
                    args.qeq_qstep if args.qeq_style in {"dynamic", "fire"} else None
                ),
                "alpha": args.slater_alpha if args.qeq_style == "slater" else None,
            },
            "relax_settings": {
                "kspace_style": args.kspace_style,
                "kspace_tol": args.kspace_tol,
                "kspace_zero_charge_gewald": args.kspace_zero_charge_gewald,
                "auto_kspace_pair_style": args.auto_kspace_pair_style,
                "pair_style_conversion": pair_style_conversion,
                "pre_relax": {
                    "enabled": args.pre_relax == "on",
                    "qeq_active": args.use_qeq == "on",
                    "min_style": args.pre_min_style,
                    "line": args.pre_line,
                    "dmax": args.pre_dmax,
                    "etol": args.pre_etol,
                    "ftol": args.pre_ftol,
                    "maxiter": args.pre_maxiter,
                    "maxeval": args.pre_maxeval,
                },
                "box_mode": args.box_mode,
                "box_target": args.box_target,
                "box_vmax": args.box_vmax,
                "box_cycles": args.box_cycles,
                "box": {
                    "line": args.box_line,
                    "dmax": args.box_dmax,
                    "etol": args.box_etol,
                    "ftol": args.box_ftol,
                    "maxiter": args.box_maxiter,
                    "maxeval": args.box_maxeval,
                },
            },
            "resolved_qeq_parameters": resolved_qeq,
            "summary": summary_parsed,
        }
        write_status(job_dir, status_payload)

        return finish(
            JobResult(
                job_name=job_name,
                job_dir=str(job_dir),
                status=status,
                message=message,
                duration_sec=time.time() - start,
                metadata_file=str(metadata_file),
                input_file=str(input_path),
                data_file=str(data_path),
                qeq_file=str(qeq_file),
                optimize_input_file=str(optimize_input_file),
                final_data_file=(
                    str(final_data_file) if final_data_file.exists() else ""
                ),
                final_dump_file=(
                    str(final_dump_file) if final_dump_file.exists() else ""
                ),
                log_file=str(log_file),
                summary_file=str(summary_file) if summary_file.exists() else "",
                launcher_stdout=str(launcher_stdout),
                launcher_stderr=str(launcher_stderr),
            )
        )

    except subprocess.TimeoutExpired as exc:
        tb = traceback.format_exc()
        write_status(
            job_dir,
            {
                "script_version": SCRIPT_VERSION,
                "status": "failed",
                "message": f"Timed out: {exc}",
                "job_dir": str(job_dir),
                "duration_sec": time.time() - start,
                "traceback": tb,
            },
        )
        return finish(
            JobResult(
                job_name=job_dir.name,
                job_dir=str(job_dir),
                status="failed",
                message=f"Timed out: {exc}",
                duration_sec=time.time() - start,
                metadata_file=str(metadata_file),
            )
        )
    except Exception as exc:
        tb = traceback.format_exc()
        write_status(
            job_dir,
            {
                "script_version": SCRIPT_VERSION,
                "status": "failed",
                "message": str(exc),
                "job_dir": str(job_dir),
                "duration_sec": time.time() - start,
                "traceback": tb,
            },
        )
        return finish(
            JobResult(
                job_name=job_dir.name,
                job_dir=str(job_dir),
                status="failed",
                message=str(exc),
                duration_sec=time.time() - start,
                metadata_file=str(metadata_file),
            )
        )


def write_manifest(jobs_root: Path, results: Iterable[Dict[str, Any]]) -> Path:
    manifest = jobs_root / "relax_manifest.csv"
    rows = list(results)
    fieldnames = [
        "job_name",
        "job_dir",
        "status",
        "message",
        "duration_sec",
        "metadata_file",
        "input_file",
        "data_file",
        "qeq_file",
        "optimize_input_file",
        "final_data_file",
        "final_dump_file",
        "log_file",
        "summary_file",
        "launcher_stdout",
        "launcher_stderr",
    ]
    with manifest.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k, "") for k in fieldnames})
    return manifest


def main(argv: Optional[List[str]] = None) -> int:
    args = parse_args(argv)
    if args.use_qeq == "on":
        qeq_cfg = load_qeq_config(args.qeq_json.resolve())
    else:
        qeq_cfg = {}
    job_dirs = collect_job_dirs(args.jobs_root.resolve(), args.recursive)
    if not job_dirs:
        print(f"No metadata.json files found under {args.jobs_root}", file=sys.stderr)
        return 2

    workers = default_workers(args.processes)
    results: List[Dict[str, Any]] = []
    args_dict = vars(args).copy()
    args_dict["jobs_root"] = str(args.jobs_root)
    args_dict["qeq_json"] = str(args.qeq_json) if args.qeq_json is not None else None

    with cf.ProcessPoolExecutor(max_workers=workers) as ex:
        futures = {
            ex.submit(run_single_job, str(job_dir), args_dict, qeq_cfg): job_dir
            for job_dir in job_dirs
        }
        for fut in tqdm(
            cf.as_completed(futures),
            total=len(futures),
            desc="Running LAMMPS relaxations",
            unit="structure",
        ):
            job_dir = futures[fut]
            try:
                result = fut.result()
            except Exception as exc:
                result = asdict(
                    JobResult(
                        job_name=job_dir.name,
                        job_dir=str(job_dir),
                        status="failed",
                        message=f"Worker failed: {exc}",
                        duration_sec=0.0,
                    )
                )
            results.append(result)

    manifest = write_manifest(args.jobs_root.resolve(), results)
    n_success = sum(r["status"] == "success" for r in results)
    n_failed = sum(r["status"] == "failed" for r in results)
    n_skipped = sum(r["status"] == "skipped" for r in results)

    print(f"\nCompleted: success={n_success}, failed={n_failed}, skipped={n_skipped}")
    print(f"manifest: {manifest}")
    return 0 if n_failed == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
