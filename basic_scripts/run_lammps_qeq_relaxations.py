#!/usr/bin/env python3
"""
Batch-run LAMMPS charge equilibration + structure optimization jobs prepared by
prepare_lammps_jobs_framework_only.py.

Workflow per job directory:
1. Read metadata.json produced by script 1
2. Build a structure-specific qeq.params file
3. Sanitize the original in.<name> into a base force-field include file
4. Generate an in.optimize wrapper that:
   - reuses the original force-field setup from lammps-interface
   - forces a KSpace solver even if the original CIF had zero charges
   - performs one-time QEq pre-charging via run 0
   - performs fixed-cell atomic relaxation with QEq active
   - performs a final atom + cell box/relax cycle with QEq active
   - writes final.data and an optional lammpstrj trajectory
5. Run LAMMPS in parallel across job directories

LAMMPS runs in long-lived worker processes through its Python module (--runner
library, the default): starting LAMMPS once per worker instead of once per job
removes most of the per-job launch cost. --runner subprocess launches --lmp-cmd
for every job as before.

Supercell jobs written by to_lammps_data.py (replication other than 1x1x1) are
relaxed under the lattice translations of the original unit cell: the copies are
first placed exactly on those translations, and at every force evaluation a fix
external callback replaces the force on each copy by the mean force over all
copies of the same unit-cell atom. The supercell then stays translation
symmetric up to round-off, so export_lammps_results_to_cif.py can take copy 0 as
the relaxed unit cell. This needs --runner library and runs LAMMPS serially.

After a job finishes, its relaxed bonds are compared with the intended ones
(the check export_lammps_results_to_cif.py applies). If they differ, the job is
run once more with --retry-fire-steps steps of FIRE appended to stage 1. The
line-search minimizers can stall in strained states, because the Dreiding
umbrella improper in LAMMPS changes its energy discontinuously when the
out-of-plane atom crosses to the side of its two neighbours; FIRE follows the
forces only and gets past it. The first attempt's outputs are kept with an
.attempt1 suffix. If the retry itself fails, the first attempt is restored.

QEq can diverge (charges in the thousands of e), for example when a collapsed
angle brings a 1-3 pair to a few hundredths of an Angstrom: qeq/point does not
exclude bonded pairs and uses an unshielded 1/r. The next minimize then sets
PPPM up for those charges, needs a grid of tens of GB and effectively never
finishes. Before every minimize and before write_data the input therefore
compares the largest |q| with --qeq-max-charge and stops the job with a LAMMPS
error when it is larger; the job is reported as failed.

The script is intentionally conservative at the force-field level, but its
default optimization recipe is tuned for coarse pre-DFT cleanup:
- it does not try to rebuild Dreiding parameters itself
- it reuses the force-field and topology generated by lammps-interface
- it expects the user to supply a QEq parameter JSON file
- it prioritizes repairing obviously bad initial geometries over tight convergence

Supported QEq styles in this wrapper: qeq/point, qeq/dynamic, qeq/fire,
qeq/shielded, qeq/slater.

Recommended JSON format (keys are examples only):
{
  "defaults": {
    "gamma": 0.0,
    "zeta": 0.0,
    "qcore": 0.0,
    "qmin": 0.0,
    "qmax": 0.0,
    "omega": 0.0
  },
  "by_force_field_type": {
    "C_R":  {"chi": 5.343, "eta": 10.126},
    "H_":   {"chi": 4.528, "eta": 13.890},
    "O_3":  {"chi": 8.741, "eta": 13.364},
    "N_R":  {"chi": 6.899, "eta": 11.760}
  },
  "by_lammps_type": {
    "7": {"chi": 5.900, "eta": 12.500}
  }
}

Resolution order for each atom type:
by_lammps_type > by_force_field_type

For maximum compatibility with LAMMPS, qeq.params is written with 8 numeric
parameters after the atom type:
chi eta gamma zeta qcore qmin qmax omega
Unused values are filled from defaults or 0.0.
"""

