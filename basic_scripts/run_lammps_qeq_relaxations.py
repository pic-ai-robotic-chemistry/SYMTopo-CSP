def sanitize_for_json(obj: Any) -> Any:
    if obj is None or isinstance(obj, (str, int, float, bool)):
        return obj
    if isinstance(obj, Path):
        return str(obj)
    if isinstance(obj, dict):
        return {str(k): sanitize_for_json(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple, set)):
        return [sanitize_for_json(v) for v in obj]
    if hasattr(obj, "item"):
        try:
            return obj.item()
        except Exception:
            pass
    if hasattr(obj, "tolist"):
        try:
            return obj.tolist()
        except Exception:
            pass
    return str(obj)


def write_json(path: Path, payload: Dict[str, Any]) -> None:
    with path.open("w", encoding="utf-8") as fh:
        json.dump(sanitize_for_json(payload), fh, ensure_ascii=False, indent=2)


def default_workers(user_value: Optional[int]) -> int:
    if user_value is not None and user_value > 0:
        return user_value
    cpu = os.cpu_count() or 1
    return max(1, cpu - 1)


def load_json(path: Path) -> Dict[str, Any]:
    with path.open("r", encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise ValueError(f"The top level of the JSON file must be an object: {path}")
    return data


def collect_job_dirs(root: Path, recursive: bool) -> List[Path]:
    pattern = "**/metadata.json" if recursive else "*/metadata.json"
    return sorted(p.parent for p in root.glob(pattern) if p.is_file())


