def discover_original_files(
    metadata: Dict[str, Any], job_dir: Path
) -> Tuple[Path, Path]:
    outputs = metadata.get("output_files", {})
    input_file = outputs.get("input_file")
    data_file = outputs.get("data_file")
    if not input_file or not data_file:
        raise ValueError(
            "metadata.json is missing output_files.input_file or output_files.data_file: "
            f"{job_dir}"
        )
    input_path = Path(input_file)
    data_path = Path(data_file)
    if not input_path.is_absolute():
        input_path = (job_dir / input_path).resolve()
    if not data_path.is_absolute():
        data_path = (job_dir / data_path).resolve()
    if not input_path.is_file():
        raise FileNotFoundError(f"Original input file not found: {input_path}")
    if not data_path.is_file():
        raise FileNotFoundError(f"Original data file not found: {data_path}")
    return input_path, data_path


def load_qeq_config(path: Path) -> Dict[str, Any]:
    cfg = load_json(path)
    cfg.setdefault("defaults", {})
    cfg.setdefault("by_force_field_type", {})
    cfg.setdefault("by_lammps_type", {})
    for key in ("defaults", "by_force_field_type", "by_lammps_type"):
        if not isinstance(cfg[key], dict):
            raise ValueError(f"{key} in the QEq configuration must be an object")
    return cfg


def resolve_qeq_params_for_type(
    atom_type: Dict[str, Any],
    qeq_cfg: Dict[str, Any],
) -> Tuple[Dict[str, float], str]:
    defaults = qeq_cfg.get("defaults", {})
    by_ff = qeq_cfg.get("by_force_field_type", {})
    by_lt = qeq_cfg.get("by_lammps_type", {})

    lammps_type = str(atom_type["lammps_type"])
    ff_type = atom_type.get("force_field_type")

    source = None
    raw: Optional[Dict[str, Any]] = None
    if lammps_type in by_lt:
        raw = by_lt[lammps_type]
        source = f"by_lammps_type:{lammps_type}"
    elif ff_type in by_ff:
        raw = by_ff[ff_type]
        source = f"by_force_field_type:{ff_type}"

    if raw is None:
        raise KeyError(
            f"Missing QEq parameters: lammps_type={lammps_type}, force_field_type={ff_type!r}"
        )
    if not isinstance(raw, dict):
        raise TypeError(f"The QEq parameter entry must be an object: {source}")

    merged: Dict[str, float] = {}
    for key in ("chi", "eta", "gamma", "zeta", "qcore", "qmin", "qmax", "omega"):
        value = raw.get(key, defaults.get(key, 0.0))
        merged[key] = float(value)
    return merged, source


def validate_qeq_coverage(
    metadata: Dict[str, Any], qeq_cfg: Dict[str, Any], qeq_style: str
) -> List[Dict[str, Any]]:
    atom_types = metadata.get("atom_types", [])
    if not atom_types:
        raise ValueError("metadata.json does not contain atom_types")

    resolved: List[Dict[str, Any]] = []
    for entry in atom_types:
        params, source = resolve_qeq_params_for_type(entry, qeq_cfg)
        if "chi" not in params or "eta" not in params:
            raise ValueError(f"Atom type {entry.get('lammps_type')} is missing chi/eta")
        if qeq_style == "shielded" and params["gamma"] == 0.0:
            raise ValueError(
                f"qeq/shielded requires nonzero gamma: lammps_type={entry.get('lammps_type')}"
            )
        if qeq_style == "slater" and params["zeta"] == 0.0 and params["qcore"] == 0.0:
            raise ValueError(
                f"qeq/slater generally requires zeta/qcore: lammps_type={entry.get('lammps_type')}"
            )
        resolved.append(
            {
                "lammps_type": int(entry["lammps_type"]),
                "force_field_type": entry.get("force_field_type"),
                "element": entry.get("element"),
                "source": source,
                **params,
            }
        )
    return sorted(resolved, key=lambda x: x["lammps_type"])


def write_qeq_params(path: Path, resolved_rows: List[Dict[str, Any]]) -> None:
    lines = ["# type chi eta gamma zeta qcore qmin qmax omega\n"]
    for row in resolved_rows:
        lines.append(
            f"{row['lammps_type']:d} "
            f"{row['chi']:.16g} {row['eta']:.16g} {row['gamma']:.16g} "
            f"{row['zeta']:.16g} {row['qcore']:.16g} {row['qmin']:.16g} "
            f"{row['qmax']:.16g} {row['omega']:.16g} "
            f"# {row.get('force_field_type', '')} {row.get('element', '')} [{row['source']}]\n"
        )
    path.write_text("".join(lines), encoding="utf-8")


def sanitize_original_input_text(text: str) -> str:
    """
    Keep the original force-field setup, but comment out runtime commands that would
    conflict with the wrapper optimization workflow.
    """
    blacklist_prefixes = [
        "run ",
        "minimize",
        "fix ",
        "unfix ",
        "dump ",
        "dump_modify",
        "undump ",
        "write_data",
        "write_dump",
        "write_restart",
        "restart ",
        "thermo ",
        "thermo_style",
        "thermo_modify",
        "velocity ",
        "reset_timestep",
        "log ",
        "shell ",
        "clear",
        "box ",
        "print ",
        "variable ",
    ]
    lines_out: List[str] = []
    for line in text.splitlines(keepends=True):
        stripped = line.lstrip()
        lowered = stripped.lower()
        if stripped.startswith("#") or stripped == "":
            lines_out.append(line)
            continue
        if any(lowered.startswith(prefix) for prefix in blacklist_prefixes):
            lines_out.append(f"# [run_lammps_qeq_relaxations.py disabled] {line}")
        else:
            lines_out.append(line)
    return "".join(lines_out)


LONG_RANGE_PAIR_TOKENS = (
    "coul/long",
    "tip4p/long",
    "lj/long",
    "buck/long",
    "dipole/long",
)

KSPACE_PAIR_STYLE_FALLBACKS = {
    "lj/cut": "lj/cut/coul/long",
    "lj/cut/coul/cut": "lj/cut/coul/long",
    "buck": "buck/coul/long",
    "buck/coul/cut": "buck/coul/long",
    "coul/cut": "coul/long",
}


def input_supports_kspace(text: str) -> bool:
    """Return True if the original input defines a long-range-compatible pair style."""
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        lowered = stripped.lower()
        if lowered.startswith("pair_style"):
            return any(tok in lowered for tok in LONG_RANGE_PAIR_TOKENS)
    return False


def convert_pair_style_for_kspace(text: str) -> Tuple[str, Dict[str, str]]:
    """Convert a known non-long-range pair style without changing the source file."""
    lines = text.splitlines(keepends=True)
    for index, line in enumerate(lines):
        body = line.rstrip("\r\n")
        ending = line[len(body) :]
        code, marker, comment = body.partition("#")
        match = re.match(r"^(\s*pair_style\s+)(\S+)(.*)$", code, flags=re.IGNORECASE)
        if match is None:
            continue
        old_style = match.group(2)
        new_style = KSPACE_PAIR_STYLE_FALLBACKS.get(old_style.lower())
        if new_style is None:
            supported = ", ".join(sorted(KSPACE_PAIR_STYLE_FALLBACKS))
            raise ValueError(
                f"pair_style {old_style} cannot be converted automatically to a KSpace-compatible form; "
                f"supported conversions: {supported}. Modify the force field manually or use --use-qeq off."
            )
        lines[index] = (
            f"{match.group(1)}{new_style}{match.group(3)}{marker}{comment}{ending}"
        )
        return "".join(lines), {"from": old_style, "to": new_style}
    raise ValueError(
        "No convertible pair_style command was found in the original input."
    )


def input_has_kspace_style(text: str) -> bool:
    """Return True if the original input already configures a KSpace solver."""
    return any(
        raw.strip().lower().startswith("kspace_style")
        for raw in text.splitlines()
        if raw.strip() and not raw.lstrip().startswith("#")
    )


def build_qeq_fix_command(args: argparse.Namespace, qeq_file_name: str) -> str:
    style = f"qeq/{args.qeq_style}"
    parts = [
        f"fix qeqfix {args.qeq_group} {style} {int(args.qeq_nevery)} {float(args.qeq_cutoff):.16g} "
        f"{qeq_tolerance(args):.16g} {int(args.qeq_maxiter)} {qeq_file_name}"
    ]
    if args.qeq_style in {"dynamic", "fire"}:
        parts.append(
            f" qdamp {float(args.qeq_qdamp):.16g} qstep {float(args.qeq_qstep):.16g}"
        )
    elif args.qeq_style == "slater" and args.slater_alpha is not None:
        parts.append(f" alpha {float(args.slater_alpha):.16g}")
    parts.append(f" warn {args.qeq_warn}")
    return "".join(parts)


def build_box_relax_command(args: argparse.Namespace) -> Optional[str]:
    if args.box_mode == "none" or args.box_cycles <= 0:
        return None
    return (
        f"fix boxrelax all box/relax {args.box_mode} {float(args.box_target):.16g} "
        f"vmax {float(args.box_vmax):.16g}"
    )


def build_charge_guard(args: argparse.Namespace) -> str:
    """Input line that stops the job when QEq has diverged; empty if disabled.

    quit would end the worker process under --runner library (it calls exit).
    Substituting an undefined variable raises an ordinary LAMMPS error instead:
    the lmp binary exits with status 1 and the Python module raises an
    exception.
    """
    if args.use_qeq != "on" or args.qeq_max_charge <= 0:
        return ""
    limit = f"{float(args.qeq_max_charge):.16g}"
    return (
        f'if "${{qmaxv}} > {limit}" then '
        f'"print \'phase=qeq_guard_failed step=${{stepv}} qmax=${{qmaxv}} limit={limit}\' append {args.summary_name}" '
        '"print ${QEq_charges_diverged}"\n'
    )


def build_optimize_input(
    args: argparse.Namespace,
    metadata: Dict[str, Any],
    base_include_name: str,
    qeq_file_name: str,
    enable_kspace: bool,
    has_kspace_style: bool,
    fire_steps: int = 0,
) -> str:
    """Build in.optimize; fire_steps > 0 appends that many FIRE steps to stage 1."""
    use_qeq = args.use_qeq == "on"
    qeq_cmd = build_qeq_fix_command(args, qeq_file_name) if use_qeq else ""
    box_cmd = build_box_relax_command(args)
    guard = build_charge_guard(args)
    traj_block = ""
    if args.dump_every > 0:
        traj_block = (
            f"dump relaxdump all custom {int(args.dump_every)} {args.trajectory_name} id type q x y z\n"
            "dump_modify relaxdump sort id\n"
        )

    summary = args.summary_name
    stage1_lines = ""
    if args.pre_relax == "on":
        stage1_lines = (
            f"{guard}"
            f"min_style {args.pre_min_style}\n"
            f"min_modify dmax {float(args.pre_dmax):.16g} line {args.pre_line}\n"
            f"minimize {float(args.pre_etol):.16g} {float(args.pre_ftol):.16g} {int(args.pre_maxiter)} {int(args.pre_maxeval)}\n"
        )
    if fire_steps > 0:
        stage1_lines += (
            "# Topology retry: FIRE moves along the forces without a line search,\n"
            "# so it gets past the energy jumps the umbrella improper can produce.\n"
            f"{guard}"
            "min_style fire\n"
            f"minimize 0.0 {float(args.pre_ftol):.16g} {int(fire_steps)} {10 * int(fire_steps)}\n"
        )
    pre_block = ""
    if stage1_lines:
        pre_block = (
            "# Stage 1: fixed-cell atomic relaxation; QEq is already active when enabled.\n"
            f'print "phase=pre_relax_start" append {summary}\n'
            f"{stage1_lines}"
            f'print "phase=pre_relax_done step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} qsum=${{qsumv}}" append {summary}\n\n'
        )

    box_cycles_lines = ""
    if box_cmd is not None:
        for cycle in range(1, int(args.box_cycles) + 1):
            box_cycles_lines += (
                f'print "phase=box_relax_start cycle={cycle}" append {summary}\n'
                f"{guard}"
                f"{box_cmd}\n"
                "min_style cg\n"
                f"min_modify dmax {float(args.box_dmax):.16g} line {args.box_line}\n"
                f"minimize {float(args.box_etol):.16g} {float(args.box_ftol):.16g} {int(args.box_maxiter)} {int(args.box_maxeval)}\n"
                "unfix boxrelax\n"
                f'print "phase=box_relax_done cycle={cycle} step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} qsum=${{qsumv}}" append {summary}\n'
            )

    if use_qeq and enable_kspace:
        kspace_block = (
            (
                "# Keep the original long-range solver.\n"
                if has_kspace_style
                else f"# Enable a long-range solver for the compatible pair_style.\n"
                f"kspace_style {args.kspace_style} {float(args.kspace_tol):.16g}\n"
            )
            + "# A nonzero G-ewald is required while all initial charges are zero.\n"
            + f"kspace_modify gewald {float(args.kspace_zero_charge_gewald):.16g}\n\n"
        )
    elif use_qeq:
        kspace_block = (
            "# No long-range-compatible pair_style detected; skip kspace_style.\n\n"
        )
    else:
        kspace_block = "# QEq disabled: preserve the original KSpace configuration.\n\n"

    if use_qeq:
        qeq_block = (
            "# Enable QEq before Stage 1 and keep it active through Stage 2.\n"
            f"{qeq_cmd}\n\n"
            "# One-time precharge before the first minimization.\n"
            "run 0\n"
            f'print "phase=precharge_done step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} qsum=${{qsumv}}" append {summary}\n\n'
            "# Charges now exist, so let LAMMPS choose G-ewald from the requested accuracy.\n"
            "kspace_modify gewald 0.0\n\n"
        )
    else:
        qeq_block = "# QEq disabled: both optimization stages run without charge equilibration.\n\n"

    return f"""# Generated by run_lammps_qeq_relaxations.py v{SCRIPT_VERSION}
# Source job: {metadata.get('job_name', 'unknown')}
# This wrapper reuses the original lammps-interface force-field setup.

include {base_include_name}

{kspace_block}# Wrapper-owned output and minimization controls
thermo 50
thermo_style custom step pe etotal press vol lx ly lz xy xz yz
{traj_block}compute qcharge all property/atom q
compute qsum all reduce sum c_qcharge
variable absq atom abs(q)
compute qmax all reduce max v_absq
variable stepv equal step
variable pev equal pe
variable pressv equal press
variable volv equal vol
variable lxv equal lx
variable lyv equal ly
variable lzv equal lz
variable xyv equal xy
variable xzv equal xz
variable yzv equal yz
variable qsumv equal c_qsum
variable qmaxv equal c_qmax

shell rm -f {summary}
print "phase=begin" append {summary}

{qeq_block}{pre_block}# Stage 2: final optional atom + cell box relaxation.
{box_cycles_lines}# Final state export.
{guard}write_data {args.final_data_name}
print "phase=final step=${{stepv}} pe=${{pev}} press=${{pressv}} vol=${{volv}} lx=${{lxv}} ly=${{lyv}} lz=${{lzv}} xy=${{xyv}} xz=${{xzv}} yz=${{yzv}} qsum=${{qsumv}}" append {summary}
"""


